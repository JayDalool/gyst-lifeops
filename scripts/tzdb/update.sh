#!/usr/bin/env bash
# Rebuilds GYST's pinned time zone database, internal/tzdb/zoneinfo.zip, from
# the IANA release named below, and writes internal/tzdb/PROVENANCE (Issue
# #193). The build is Go's own lib/time/update.bash recipe, so the zip has the
# same format and content rules as Go's embedded copy, just a newer release.
#
#   scripts/tzdb/update.sh           rebuild and replace the pinned files
#   scripts/tzdb/update.sh --check   rebuild and confirm the committed files
#                                    are byte-identical (reproducibility)
#
# Needs bash, curl, tar, make, a C compiler, awk, sha512sum, sha256sum and go.
# gpg is required to adopt a new release and optional for --check, where the
# pinned SHA-512 values already fix the exact source bytes.
#
# Moving to a new release: set VERSION and both SHA512 values from the IANA
# announcement (tz-announce), run without --check, review the diff and the
# NEWS for the release, and run the whole test suite.
set -euo pipefail

VERSION=2026f
TZCODE_SHA512=eefcea60c37857214e1eba768d1bbd096de2a8f5afc9a776555552922cc174b32892d7442097b699b77efcba4d85649ed7d13e752ffdbcaad1050749c6c7b5aa
TZDATA_SHA512=26189803c8b3e903dcc467404e2feefb7d190cb1870249a23577ce31e9dcbf187e4704e0b45c8d1366d1c501bb5b53a2e80f8e2828b2163be15e532f6acab52d
# Paul Eggert's tz release signing key (primary key fingerprint).
SIGNING_KEY=7E3792A9D8ACF7D633BC1588ED97E90E62AA7E34
BASE=https://data.iana.org/time-zones/releases
MAKE_ARGS=(CFLAGS=-DSTD_INSPIRED AWK=awk PACKRATDATA=backzone PACKRATLIST=zone.tab)

mode=update
case "${1:-}" in
  "") ;;
  --check) mode=check ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

repo=$(cd "$(dirname "$0")/../.." && pwd)
out=$repo/internal/tzdb
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
code=tzcode$VERSION.tar.gz
data=tzdata$VERSION.tar.gz

echo "== download $VERSION from $BASE"
for f in "$code" "$data"; do
  curl -fsS --proto '=https' --tlsv1.2 -o "$work/$f" "$BASE/$f"
  curl -fsS --proto '=https' --tlsv1.2 -o "$work/$f.asc" "$BASE/$f.asc"
done

echo "== verify SHA-512 pins"
(cd "$work" && printf '%s  %s\n%s  %s\n' "$TZCODE_SHA512" "$code" "$TZDATA_SHA512" "$data" | sha512sum -c -)

echo "== verify signatures"
if command -v gpg >/dev/null 2>&1; then
  export GNUPGHOME="$work/gnupg"
  mkdir -m 700 "$GNUPGHOME"
  curl -fsS --proto '=https' --tlsv1.2 -o "$work/key.asc" \
    "https://keys.openpgp.org/vks/v1/by-fingerprint/$SIGNING_KEY"
  gpg -q --import "$work/key.asc"
  gpg --with-colons --fingerprint | grep -q "^fpr:::::::::$SIGNING_KEY:$" ||
    { echo "fetched key is not $SIGNING_KEY" >&2; exit 1; }
  for f in "$code" "$data"; do
    gpg --status-fd 1 --verify "$work/$f.asc" "$work/$f" 2>/dev/null |
      grep -q "^\[GNUPG:\] VALIDSIG .* $SIGNING_KEY$" ||
      { echo "bad or missing signature on $f" >&2; exit 1; }
    echo "$f: good signature from $SIGNING_KEY"
  done
elif [ "$mode" = check ]; then
  echo "gpg not found: signatures not checked (the SHA-512 pins were)"
else
  echo "gpg is required to adopt a release" >&2
  exit 1
fi

echo "== build zone files"
mkdir "$work/src" "$work/zoneinfo"
tar -xzf "$work/$code" -C "$work/src"
tar -xzf "$work/$data" -C "$work/src"
[ "$(cat "$work/src/version")" = "$VERSION" ] || { echo "tarball version mismatch" >&2; exit 1; }
# The zip holds only compiled zone data, which tzdb places in the public
# domain (its few BSD-licensed files are code GYST does not use). Stop if a
# release ever says otherwise.
tr '\n' ' ' <"$work/src/LICENSE" | grep -q 'all files in the tz code and data (including this LICENSE file) are in the public domain' ||
  { echo "tzdb LICENSE no longer says public domain: review it before adopting $VERSION" >&2; exit 1; }
if ! make -C "$work/src" "${MAKE_ARGS[@]}" TZDIR="$work/zoneinfo" posix_only >"$work/make.log" 2>&1; then
  cat "$work/make.log"
  exit 1
fi
(cd "$repo" && go build -trimpath -o "$work/mkzip" ./scripts/tzdb/mkzip)
zones=$("$work/mkzip" "$work/zoneinfo" "$work/zoneinfo.zip" | awk '{print $1}')
sha=$(sha256sum "$work/zoneinfo.zip" | awk '{print $1}')

cat >"$work/PROVENANCE" <<EOF
# GYST's pinned IANA time zone database (Issue #193).
# Generated by scripts/tzdb/update.sh; do not edit by hand.
tzdb_version=$VERSION
source=$BASE/
tzcode=$code
tzcode_sha512=$TZCODE_SHA512
tzdata=$data
tzdata_sha512=$TZDATA_SHA512
signing_key=$SIGNING_KEY
license=public domain (tzdb LICENSE)
build=make ${MAKE_ARGS[*]} posix_only (Go lib/time/update.bash recipe)
zip=scripts/tzdb/mkzip (stored, lexical order, no timestamps)
zones=$zones
zoneinfo_zip_sha256=$sha
EOF

if [ "$mode" = check ]; then
  cmp "$work/zoneinfo.zip" "$out/zoneinfo.zip" && cmp "$work/PROVENANCE" "$out/PROVENANCE" ||
    { echo "MISMATCH: the committed files do not match a fresh build" >&2; exit 1; }
  echo "OK: rebuilt $VERSION; zoneinfo.zip ($sha, $zones zones) and PROVENANCE are byte-identical"
else
  mkdir -p "$out"
  cp "$work/zoneinfo.zip" "$work/PROVENANCE" "$out/"
  echo "updated $out: tzdb $VERSION, $zones zones, sha256 $sha"
fi
